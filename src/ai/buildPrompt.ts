export interface TrainingWithShots {
  training: TrainingRecord;
  shots: ShotRecord[];
  comments: CommentRecord[];
  /** General remarks on the whole training and its series (see PLAN-AI-ANALYSIS.md). */
  trainingComments: string[];
}

export function buildUserPrompt(trainings: TrainingWithShots[]): string {
  const data = trainings.map(({ training, shots, comments, trainingComments }) => {
    const committed = shots.filter(s => s.status === 'committed');
    return {
      date: training.startedAt.slice(0, 10),
      startedAt: training.startedAt,
      completedAt: training.completedAt,
      targetShotCount: training.targetShotCount ?? null,
      shotCount: committed.length,
      ...(trainingComments.length > 0 ? { trainingComments } : {}),
      shots: committed.map(s => {
        const shotComments = comments.filter(c => c.shotId === s.id).map(c => c.text);
        return {
          shotNumber: s.shotNumber,
          score: s.score, // внутренняя шкала: 104 = 10.4 ISSF decimal
          x: s.x, // сотые мм, положительный = правее центра
          y: s.y, // сотые мм, положительный = выше центра
          createdAt: s.createdAt,
          ...(shotComments.length > 0 ? { comments: shotComments } : {}),
        };
      }),
    };
  });

  return JSON.stringify(data);
}
